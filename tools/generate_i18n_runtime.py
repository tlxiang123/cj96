def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\r\n", "\n").replace("\n", "\\n") + '"'


def load_rows() -> list[dict[str, str]]:
    with SOURCE.open("r", encoding="utf-8-sig", newline="") as handle:
        rows = list(csv.DictReader(handle))
    result: list[dict[str, str]] = []
    seen: set[tuple[str, str, str]] = set()
    for row in rows:
        if row.get("字段名") != "text":
            continue
        ftu = row.get("所在FTU", "")
        control_id = row.get("控件ID", "")
        key = (ftu, control_id, row.get("字段名", ""))
        if not ftu or not control_id or key in seen:
            continue
        seen.add(key)
        result.append(row)
    return result




RUNTIME_HEADER = "static const DynamicMapping RUNTIME_TEXTS[] = {"


def dedupe_runtime_texts(lines: list[str]) -> list[str]:
    """Drop duplicate RUNTIME_TEXTS keys, keeping the first occurrence.

    translateRuntimeText() scans the table linearly and returns the first
    match, so any later duplicate was already unreachable dead data.  Keeping
    the first occurrence therefore preserves the exact previous behaviour
    while making the generated table deterministic.
    """
    try:
        start = lines.index(RUNTIME_HEADER)
    except ValueError:
        return lines
    end = start + 1
    while end < len(lines) and lines[end] != "};":
        end += 1

    kept: list[str] = []
    seen: set[str] = set()
    for index in range(start + 1, end):
        line = lines[index]
        stripped = line.strip()
        if not (stripped.startswith("{\"") and ", {" in stripped):
            continue
        key = stripped[2:stripped.index(", {")]
        if key in seen:
            continue
        seen.add(key)
        kept.append(line)

    return lines[:start + 1] + kept + lines[end:]


