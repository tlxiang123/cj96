static const char* PRIMARY_LANGUAGE_PATH = "/data/cj96_language.txt";
static const char* FALLBACK_LANGUAGE_PATH = "/mnt/extsd/cj96_language.txt";

static int normalizeLanguage(int value) {
    return (value >= 0 && value < LANG_COUNT) ? value : LANG_ZH;
}

static int readLanguageFromPath(const char* path) {
    FILE* file = fopen(path, "rb");
    if (!file) return -1;
    char buffer[16] = {0};
    size_t count = fread(buffer, 1, sizeof(buffer) - 1, file);
    fclose(file);
    if (count == 0) return -1;
    return atoi(buffer);
}

static int getLanguage() {
    int value = readLanguageFromPath(PRIMARY_LANGUAGE_PATH);
    if (value < 0) value = readLanguageFromPath(FALLBACK_LANGUAGE_PATH);
    return normalizeLanguage(value);
}

static void writeLanguageToPath(const char* path, int language) {
    FILE* file = fopen(path, "wb");
    if (!file) return;
    fprintf(file, "%d\n", normalizeLanguage(language));
    fflush(file);
    fclose(file);
}

static void setLanguage(int language) {
    language = normalizeLanguage(language);
    writeLanguageToPath(PRIMARY_LANGUAGE_PATH, language);
    writeLanguageToPath(FALLBACK_LANGUAGE_PATH, language);
}

