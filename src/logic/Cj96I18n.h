static const char* translateRuntimeText(const char* source, int language) {
    if (!source) return source;
    language = normalizeLanguage(language);
    if (language == LANG_ZH) return source;
    for (size_t i = 0; i < sizeof(RUNTIME_TEXTS) / sizeof(RUNTIME_TEXTS[0]); ++i) {
        if (std::strcmp(RUNTIME_TEXTS[i].source, source) == 0) return RUNTIME_TEXTS[i].text[language - 1];
    }
    return source;
}

